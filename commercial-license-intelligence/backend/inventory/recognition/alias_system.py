class IdentitySignalType(str, Enum):
    EXACT_DISPLAY_NAME = "EXACT_DISPLAY_NAME"
    PUBLISHER_AND_PRODUCT = "PUBLISHER_AND_PRODUCT"
    EXECUTABLE_MATCH = "EXECUTABLE_MATCH"
    PACKAGE_FAMILY_MATCH = "PACKAGE_FAMILY_MATCH"
    ALIAS_MATCH = "ALIAS_MATCH"
    FUZZY_NAME_MATCH = "FUZZY_NAME_MATCH"
    UNKNOWN = "UNKNOWN"


# Signal Score Weights (Part 13)
SIGNAL_SCORES: Dict[IdentitySignalType, float] = {
    IdentitySignalType.EXACT_DISPLAY_NAME: 100.0,
    IdentitySignalType.PUBLISHER_AND_PRODUCT: 95.0,
    IdentitySignalType.EXECUTABLE_MATCH: 90.0,
    IdentitySignalType.PACKAGE_FAMILY_MATCH: 90.0,
    IdentitySignalType.ALIAS_MATCH: 80.0,
    IdentitySignalType.FUZZY_NAME_MATCH: 60.0,
    IdentitySignalType.UNKNOWN: 0.0,
}


@dataclass
class ResolvedApplicationIdentity:
    """Canonical application identity resolved from multi-source signals."""
    raw_name: str
    raw_publisher: Optional[str]
    detected_version: Optional[str]
    canonical_product: str
    canonical_vendor: str
    product_type: str  # COMMERCIAL_APPLICATION, COMMERCIAL_COMPONENT, OPEN_SOURCE_APPLICATION, FREEWARE, OS_BUNDLED, UNKNOWN
    parent_product: Optional[str]
    confidence_score: float
    matched_signal: IdentitySignalType
    detection_source: str
    matched_alias: Optional[str] = None
    notes: str = ""



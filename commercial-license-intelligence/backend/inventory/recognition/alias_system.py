    @classmethod
    def resolve_application(
        cls,
        raw_name: str,
        raw_publisher: Optional[str] = None,
        raw_version: Optional[str] = None,
        executable_name: Optional[str] = None,
        package_family_name: Optional[str] = None,
        install_location: Optional[str] = None,
        detection_source: Optional[str] = None,
    ) -> ResolvedApplicationIdentity:
        """
        Multi-signal application identity resolution adhering to Part 13 & Part 16 priorities.
        Priority:
        1. Exact Display Name / Alias Match (100 / 80)
        2. Publisher + Product Combination (95)
        3. Executable Identity Match (90)
        4. Package Family Match (90)
        5. Fuzzy Name Match (60)
        """
        n_clean = (raw_name or "").strip()
        n_low = unicodedata.normalize("NFKC", n_clean).lower().replace("®", "").replace("™", "").strip()
        n_orig_low = n_clean.lower()
        p_clean = (raw_publisher or "").strip()
        p_low = p_clean.lower()
        exec_low = (executable_name or "").strip().lower()
        pkg_fam_low = (package_family_name or "").strip().lower()
        source_str = detection_source or "ENDPOINT_SCAN"

        # Signal 1: Package Family Name Match (Score: 90)
        if pkg_fam_low and pkg_fam_low in cls._PACKAGE_FAMILY_MAP:
            m = cls._PACKAGE_FAMILY_MAP[pkg_fam_low]
            return ResolvedApplicationIdentity(
                raw_name=raw_name,
                raw_publisher=raw_publisher,
                detected_version=raw_version,
                canonical_product=m["canonical_product"],
                canonical_vendor=m["canonical_vendor"],
                product_type=m["product_type"],
                parent_product=m.get("parent_product"),
                confidence_score=SIGNAL_SCORES[IdentitySignalType.PACKAGE_FAMILY_MATCH],
                matched_signal=IdentitySignalType.PACKAGE_FAMILY_MATCH,
                detection_source=source_str,
                matched_alias=pkg_fam_low,
                notes="Matched via Windows Modern Package Family Name.",
            )

        # Signal 2: Executable Match (Score: 90)
        if exec_low:
            exec_basename = exec_low.replace("\\", "/").split("/")[-1]
            if exec_basename in cls._EXECUTABLE_MAP:
                m = cls._EXECUTABLE_MAP[exec_basename]
                return ResolvedApplicationIdentity(
                    raw_name=raw_name,
                    raw_publisher=raw_publisher,
                    detected_version=raw_version,
                    canonical_product=m["canonical_product"],
                    canonical_vendor=m["canonical_vendor"],
                    product_type=m["product_type"],
                    parent_product=m.get("parent_product"),
                    confidence_score=SIGNAL_SCORES[IdentitySignalType.EXECUTABLE_MATCH],
                    matched_signal=IdentitySignalType.EXECUTABLE_MATCH,
                    detection_source=source_str,
                    matched_alias=exec_basename,
                    notes=f"Matched via executable binary identity ({exec_basename}).",
                )

        # Signal 3: Publisher + Product Match (Score: 95)
        combined_key = f"{p_low} {n_low}".strip()
        if "openai" in p_low and ("chatgpt" in n_low or "codex" in n_low):
            return ResolvedApplicationIdentity(
                raw_name=raw_name,
                raw_publisher=raw_publisher,
                detected_version=raw_version,
                canonical_product="ChatGPT",
                canonical_vendor="OpenAI",
                product_type="COMMERCIAL_APPLICATION",
                parent_product=None,
                confidence_score=SIGNAL_SCORES[IdentitySignalType.PUBLISHER_AND_PRODUCT],
                matched_signal=IdentitySignalType.PUBLISHER_AND_PRODUCT,
                detection_source=source_str,
                matched_alias=combined_key,
                notes="Matched via OpenAI publisher and ChatGPT/Codex product identification.",
            )

        # Signal 4: Exact Alias / Display Name Match (Score: 100 / 80)
        if n_low in cls._ALIAS_REGISTRY:
            m = cls._ALIAS_REGISTRY[n_low]
            return ResolvedApplicationIdentity(
                raw_name=raw_name,
                raw_publisher=raw_publisher,
                detected_version=raw_version,
                canonical_product=m["canonical_product"],
                canonical_vendor=m["canonical_vendor"],
                product_type=m["product_type"],
                parent_product=m.get("parent_product"),
                confidence_score=SIGNAL_SCORES[m["signal"]],
                matched_signal=m["signal"],
                detection_source=source_str,
                matched_alias=n_low,
                notes=m["notes"],
            )

        if n_orig_low in cls._ALIAS_REGISTRY:
            m = cls._ALIAS_REGISTRY[n_orig_low]
            return ResolvedApplicationIdentity(
                raw_name=raw_name,
                raw_publisher=raw_publisher,
                detected_version=raw_version,
                canonical_product=m["canonical_product"],
                canonical_vendor=m["canonical_vendor"],
                product_type=m["product_type"],
                parent_product=m.get("parent_product"),
                confidence_score=SIGNAL_SCORES[m["signal"]],
                matched_signal=m["signal"],
                detection_source=source_str,
                matched_alias=n_orig_low,
                notes=m["notes"],
            )

        # Signal 5: Fuzzy Alias Match (Score: 60)
        for k, m in cls._ALIAS_REGISTRY.items():
            k_clean = k.replace("®", "").replace("™", "").strip()
            if (len(k_clean) >= 5 and k_clean in n_low) or (len(n_low) >= 5 and n_low in k_clean):
                return ResolvedApplicationIdentity(
                    raw_name=raw_name,
                    raw_publisher=raw_publisher,
                    detected_version=raw_version,
                    canonical_product=m["canonical_product"],
                    canonical_vendor=m["canonical_vendor"],
                    product_type=m["product_type"],
                    parent_product=m.get("parent_product"),
                    confidence_score=SIGNAL_SCORES[IdentitySignalType.FUZZY_NAME_MATCH],
                    matched_signal=IdentitySignalType.FUZZY_NAME_MATCH,
                    detection_source=source_str,
                    matched_alias=k,
                    notes=f"Fuzzy match on alias '{k}'.",
                )

        # Fallback vendor resolution
        resolved_vend = raw_publisher
        if raw_publisher:
            from backend.inventory.detection.detection_normalizer import DetectionNormalizer
            norm_vend = DetectionNormalizer.normalize_publisher(raw_publisher, raw_name=raw_name)
            if norm_vend:
                resolved_vend = norm_vend

        # Signal 6: Unknown Fallback (Score: 0)
        return ResolvedApplicationIdentity(
            raw_name=raw_name,
            raw_publisher=raw_publisher,
            detected_version=raw_version,
            canonical_product=n_clean,
            canonical_vendor=resolved_vend or "Unknown",
            product_type="UNKNOWN",
            parent_product=None,
            confidence_score=SIGNAL_SCORES[IdentitySignalType.UNKNOWN],
            matched_signal=IdentitySignalType.UNKNOWN,
            detection_source=source_str,
            matched_alias=None,
            notes="No alias match found in registry.",
        )

    @classmethod
    def research_product(
        cls,
        identity: ResolvedMicrosoftIdentity,
        prev_classification: Optional[str] = None,
        prev_license_required: Optional[str] = None,
    ) -> WindowsResearchResult:
        """
        Conducts research evaluation for a resolved Microsoft/Windows application.
        Applies Part 5 categorizations and Part 6 OS_BUNDLED evidence requirements.
        """
        c_name = identity.canonical_name
        c_name_low = c_name.lower()
        p_type = identity.product_type

        # 0. Check for Unresolved Package Identity (Section 7 & 9)
        if c_name == "UNRESOLVED" or identity.identity_confidence == "UNRESOLVED":
            return WindowsResearchResult(
                canonical_name="UNRESOLVED",
                canonical_vendor="Unknown",
                product_family="Unknown",
                product_type=WindowsProductCategory.UNKNOWN,
                parent_product=None,
                is_os_bundled_proven=False,
                classification="UNKNOWN",
                availability="UNKNOWN",
                license_required="UNKNOWN",
                license_model="UNKNOWN",
                license_metric="UNKNOWN",
                evidence_status="MISSING",
                evidence_quote="Unresolved package identity. No official product-specific licensing terms exist for unmapped internal GUID/tokens.",
                source_url="https://learn.microsoft.com/en-us/windows/",
                authority_tier=SourceAuthorityTier.TIER_5,
                evidence_tier_name="NONE",
            )

        # 1. Check direct Licensing Source Adapter evidence first (for Commercial, Components, Dev Tools)
        lic_evidence = MicrosoftLicensingSourceAdapter.research_microsoft_product(
            canonical_product_name=c_name,
            product_family=identity.product_family,
            product_type=p_type.value,
        )

        if lic_evidence and lic_evidence.evidence_tier_name in ["TIER_1", "TIER_2", "TIER_3"]:
            # Strong licensing evidence found
            is_os_bundled = (lic_evidence.license_model == "Operating System Bundled Feature")
            
            # Determine classification based on product type & licensing model
            if p_type == WindowsProductCategory.COMMERCIAL_COMPONENT:
                final_class = "COMMERCIAL_COMPONENT"
            elif p_type == WindowsProductCategory.COMMERCIAL_APPLICATION:
                if lic_evidence.availability_model == "FREE_AND_PAID" or lic_evidence.license_required == "CONTEXT_DEPENDENT":
                    final_class = "FREE_AND_PAID"
                elif lic_evidence.is_commercial_license_required and lic_evidence.license_required == "YES":
                    final_class = "COMMERCIAL"
                else:
                    final_class = "FREEWARE"
            elif p_type == WindowsProductCategory.OPEN_SOURCE_APPLICATION:
                final_class = "OPEN_SOURCE"
            elif p_type in [WindowsProductCategory.FRAMEWORK_RUNTIME, WindowsProductCategory.SYSTEM_DEPENDENCY]:
                final_class = "FREEWARE"
            elif p_type == WindowsProductCategory.MICROSOFT_STORE_APP:
                if lic_evidence.availability_model == "FREE_AND_PAID" or lic_evidence.license_required == "CONTEXT_DEPENDENT":
                    final_class = "FREE_AND_PAID"
                elif lic_evidence.license_required == "YES":
                    final_class = "COMMERCIAL"
                else:
                    final_class = "FREEWARE"
            elif is_os_bundled:
                final_class = "OS_BUNDLED"
            else:
                if lic_evidence.availability_model == "FREE_AND_PAID":
                    final_class = "FREE_AND_PAID"
                elif lic_evidence.license_required in ["YES", "CONTEXT_DEPENDENT"] and lic_evidence.is_commercial_license_required:
                    final_class = "COMMERCIAL"
                else:
                    final_class = "FREEWARE"

            # Enforce binary YES/NO License Required:
            # If any applicable commercial scenario requires paid license, subscription or entitlement -> YES
            if final_class in ("COMMERCIAL", "FREE_AND_PAID", "TRIAL", "COMMERCIAL_COMPONENT") or lic_evidence.is_commercial_license_required or lic_evidence.availability_model == "FREE_AND_PAID":
                final_req = "YES"
            elif final_class in ("OS_BUNDLED", "FREEWARE", "OPEN_SOURCE"):
                final_req = "NO"
            else:
                final_req = lic_evidence.license_required

            return WindowsResearchResult(
                canonical_name=c_name,
                canonical_vendor=identity.canonical_vendor,
                product_family=identity.product_family,
                product_type=p_type,
                parent_product=lic_evidence.parent_product or identity.parent_product,
                is_os_bundled_proven=is_os_bundled,
                classification=final_class,
                availability=lic_evidence.availability_model,
                license_required=final_req,
                license_model=lic_evidence.license_model,
                license_metric=lic_evidence.license_metric,
                evidence_status="VERIFIED",
                evidence_quote=lic_evidence.evidence_text,
                source_url=lic_evidence.source_url,
                authority_tier=lic_evidence.authority_level,
                evidence_tier_name=lic_evidence.evidence_tier_name,
            )

        # 2. Check Confirmed Inbox & OS Component Registry
        if c_name_low in cls.INBOX_AND_OS_EVIDENCE:
            ev = cls.INBOX_AND_OS_EVIDENCE[c_name_low]
            return WindowsResearchResult(
                canonical_name=c_name,
                canonical_vendor=identity.canonical_vendor,
                product_family=identity.product_family,
                product_type=p_type,
                parent_product=identity.parent_product or "Microsoft Windows",
                is_os_bundled_proven=True,
                classification=ev["classification"],
                availability=ev["availability"],
                license_required=ev["license_required"],
                license_model=ev["license_model"],
                license_metric=ev["license_metric"],
                evidence_status="VERIFIED",
                evidence_quote=ev["evidence_text"],
                source_url=ev["source_url"],
                authority_tier=ev["authority_tier"],
                evidence_tier_name=ev["tier_name"],
            )

        # 3. Check Windows OS Components & Inbox Apps
        if p_type in (WindowsProductCategory.WINDOWS_OS_COMPONENT, WindowsProductCategory.WINDOWS_INBOX_APP):
            return WindowsResearchResult(
                canonical_name=c_name,
                canonical_vendor="Microsoft Windows",
                product_family=identity.product_family or "Windows OS Core Components",
                product_type=p_type,
                parent_product="Microsoft Windows",
                is_os_bundled_proven=True,
                classification="OS_BUNDLED",
                availability="BUNDLED",
                license_required="NO",
                license_model="Operating System Bundled Feature",
                license_metric="NOT_APPLICABLE",
                evidence_status="VERIFIED",
                evidence_quote=f"Windows built-in accessory or operating system component ({c_name}).",
                source_url="https://learn.microsoft.com/en-us/windows/apps/inbox-apps",
                authority_tier=SourceAuthorityTier.TIER_2,
                evidence_tier_name="TIER_2",
            )

        # 4. Check Framework Runtimes & System Dependencies
        if p_type in [WindowsProductCategory.FRAMEWORK_RUNTIME, WindowsProductCategory.SYSTEM_DEPENDENCY]:
            return WindowsResearchResult(
                canonical_name=c_name,
                canonical_vendor=identity.canonical_vendor,
                product_family=identity.product_family,
                product_type=p_type,
                parent_product=identity.parent_product,
                is_os_bundled_proven=False,
                classification="FREEWARE",
                availability="FREE",
                license_required="NO",
                license_model="Redistributable System Component",
                license_metric="NOT_APPLICABLE",
                evidence_status="VERIFIED",
                evidence_quote=f"Redistributable system component/runtime for {identity.product_family}.",
                source_url="https://learn.microsoft.com/en-us/windows/",
                authority_tier=SourceAuthorityTier.TIER_2,
                evidence_tier_name="TIER_2",
            )

        # 5. Check Microsoft Store Apps (without confirmed OS inclusion)
        if p_type == WindowsProductCategory.MICROSOFT_STORE_APP:
            return WindowsResearchResult(
                canonical_name=c_name,
                canonical_vendor=identity.canonical_vendor,
                product_family=identity.product_family,
                product_type=p_type,
                parent_product=identity.parent_product,
                is_os_bundled_proven=False,
                classification="FREEWARE",
                availability="FREE",
                license_required="NO",
                license_model="Microsoft Store Free App",
                license_metric="NOT_APPLICABLE",
                evidence_status="VERIFIED",
                evidence_quote=f"Free application available from the Microsoft Store for {c_name}.",
                source_url="https://apps.microsoft.com",
                authority_tier=SourceAuthorityTier.TIER_3,
                evidence_tier_name="TIER_3",
            )

        # 6. Part 7: No Evidence Rule - If no product-specific official evidence is found:
        # DO NOT classify as FREEWARE or OS_BUNDLED without evidence. Keep previous validated classification or UNKNOWN.
        if prev_classification in ["OS_BUNDLED", "OPEN_SOURCE / FREEWARE", "FREEWARE", "UNKNOWN", None]:
            fallback_class = "UNKNOWN"
            fallback_req = "UNKNOWN"
        else:
            fallback_class = prev_classification
            fallback_req = prev_license_required or "UNKNOWN"

        return WindowsResearchResult(
            canonical_name=c_name,
            canonical_vendor=identity.canonical_vendor,
            product_family=identity.product_family,
            product_type=p_type,
            parent_product=identity.parent_product,
            is_os_bundled_proven=False,
            classification=fallback_class,
            availability="UNKNOWN",
            license_required=fallback_req,
            license_model="UNKNOWN",
            license_metric="UNKNOWN",
            evidence_status="MISSING",
            evidence_quote="No product-specific official licensing terms found. Retaining UNKNOWN under No-Evidence Rule.",
            source_url="",
            authority_tier=SourceAuthorityTier.TIER_5,
            evidence_tier_name="TIER_5",
        )
